// Interface language. Russian text is the key, so a string missing from EN simply shows in Russian.
export type UiLanguage = 'ru' | 'en'

let language: UiLanguage = 'ru'

export const setLanguage = (l: UiLanguage): void => {
  language = l
}
export const getLanguage = (): UiLanguage => language

export function tr(key: string, ...args: unknown[]): string {
  const s = language === 'en' ? (EN[key] ?? key) : key
  return args.length === 0 ? s : s.replace(/\{(\d+)\}/g, (_, i: string) => String(args[Number(i)] ?? ''))
}

